<?php

namespace App\Console\Commands;

use App\Models\Country;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\Http;

class ImportCountriesCommand extends Command
{
    /*
    |--------------------------------------------------------------------------
    | Command Signature
    |--------------------------------------------------------------------------
    */

    protected $signature =
        'countries:import';

    /*
    |--------------------------------------------------------------------------
    | Command Description
    |--------------------------------------------------------------------------
    */

    protected $description =
        'Import countries in German language';

    /*
    |--------------------------------------------------------------------------
    | Handle Command
    |--------------------------------------------------------------------------
    */

    public function handle()
    {
        $this->info(
            'Fetching countries...'
        );

        /*
        |--------------------------------------------------------------------------
        | API Request
        |--------------------------------------------------------------------------
        */

        $response = Http::withoutVerifying()
            ->timeout(60)
            ->get(
                'https://restcountries.com/v3.1/all?fields=cca2,translations'
            );

        /*
        |--------------------------------------------------------------------------
        | Failed Response
        |--------------------------------------------------------------------------
        */

        if ($response->failed()) {

            $this->error(
                'Failed to fetch countries'
            );

            dd(
                $response->body()
            );

            return;
        }

        /*
        |--------------------------------------------------------------------------
        | Countries Data
        |--------------------------------------------------------------------------
        */

        $countries =
            $response->json();

        /*
        |--------------------------------------------------------------------------
        | Insert / Update Countries
        |--------------------------------------------------------------------------
        */

        foreach ($countries as $item) {

            /*
            |--------------------------------------------------------------------------
            | Skip Invalid Rows
            |--------------------------------------------------------------------------
            */

            if (
                !is_array($item) ||
                !isset($item['cca2'])
            ) {
                continue;
            }

            /*
            |--------------------------------------------------------------------------
            | German Country Name
            |--------------------------------------------------------------------------
            */

            $germanName =
                $item['translations']['deu']['common']
                ?? null;

            /*
            |--------------------------------------------------------------------------
            | Skip Empty Names
            |--------------------------------------------------------------------------
            */

            if (!$germanName) {
                continue;
            }

            /*
            |--------------------------------------------------------------------------
            | Insert / Update
            |--------------------------------------------------------------------------
            */

            Country::updateOrCreate(

                [
                    'code' => strtolower(
                        $item['cca2']
                    )
                ],

                [

                    'name' =>
                        $germanName,

                    'code' => strtolower(
                        $item['cca2']
                    ),

                    'status' => 1
                ]
            );
        }

        /*
        |--------------------------------------------------------------------------
        | Success Message
        |--------------------------------------------------------------------------
        */

        $this->info(

            count($countries)

            . ' countries imported successfully.'
        );
    }
}
